def build_sitemap() -> None:
    entries = [(path, freq, priority, BUILD_DATE) for path, freq, priority in C.SITEMAP]
    entries += [
        (f"/resources/{r['slug']}/", "monthly", "0.6", r["date"]) for r in D.RESOURCES
    ]
    entries += [
        (f"/blogs/{post['slug']}/", "monthly", "0.7", post["updated"])
        for post in blog_posts.all_posts()
    ]
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for path, freq, priority, lastmod in entries:
        lines.append(
            f"  <url><loc>{C.SITE_URL}{path}</loc><lastmod>{lastmod}</lastmod>"
            f"<changefreq>{freq}</changefreq><priority>{priority}</priority></url>"
        )
    lines.append("</urlset>")
    write("sitemap.xml", "\n".join(lines) + "\n")

    write("robots.txt", f"""User-agent: *
Allow: /

# Static site. No scanning endpoints, no private paths and nothing to crawl
# that is not linked from the sitemap.
Disallow: /downloads/

Sitemap: {C.SITE_URL}/sitemap.xml
""")


# ---------------------------------------------------------------------------
# Build + link check
# ---------------------------------------------------------------------------

def build() -> None:
    # Asset versions must be known before the pages that reference them render.
    apply_asset_versions()
    for rel, builder in PAGES.items():
        write(rel, builder())
    for rel, (target, title) in REDIRECTS.items():
        write(rel, pages_legal.redirect(target, title))
    build_config_js()
    build_data()
    build_downloads()
    build_sitemap()


# ---------------------------------------------------------------------------
# Static asset versioning
# ---------------------------------------------------------------------------

def digest(data: str | bytes) -> str:
    if isinstance(data, str):
        data = data.encode("utf-8")
    return hashlib.sha256(data).hexdigest()[:8]


def apply_asset_versions() -> dict[str, str]:
    """Version the unhashed, long-lived asset URLs.

    GitHub Pages always answers with `cache-control: max-age=600` and offers no
    way to change it, so a stale stylesheet or script can survive a deploy for
    up to ten minutes. Appending a content hash to the URL makes the address of
    the file change whenever its contents change, which keeps the ten-minute
    window harmless without pretending the TTL can be extended.
    """
    versions = {
        "/styles.css": digest((OUT / "styles.css").read_bytes()),
        "/site.js": digest((OUT / "site.js").read_bytes()),
        "/config.js": digest(config_js_source()),
    }
    ui.set_asset_versions(versions)
    return versions


def check_links() -> int:
    """Verify every internal href/src resolves to a file in website/."""
    problems = []
    html_files = sorted(OUT.rglob("*.html"))
    for path in html_files:
        text = path.read_text(encoding="utf-8")
        refs = re.findall(r'(?:href|src)="(/[^"#?]*)"', text)
        for ref in refs:
            if ref == "/":
                target = OUT / "index.html"
            elif ref.endswith("/"):
                target = OUT / ref.lstrip("/") / "index.html"
            else:
                target = OUT / ref.lstrip("/")
            if not target.exists():
                problems.append(f"{path.relative_to(OUT)} -> {ref}")
        anchors = re.findall(r'href="#([^"]+)"', text)
        ids = set(re.findall(r'id="([^"]+)"', text))
        for anchor in anchors:
            if anchor and anchor not in ids:
                problems.append(f"{path.relative_to(OUT)} -> #{anchor} (missing id)")

    if problems:
        print(f"link check: {len(problems)} problem(s)")
        for problem in problems:
            print("  -", problem)
        return 1
    print(f"link check: {len(html_files)} pages, all internal links resolve")
    return 0


if __name__ == "__main__":
    build()
    print(f"built {len(list(PAGES))} pages, {len(REDIRECTS)} redirects into {OUT}")
    status = 0
    if "--check" in sys.argv:
        status = check_links()
    if "--audit" in sys.argv:
        status = A.run(OUT, C, D, PAGES, REDIRECTS) or status
    sys.exit(status)
