def config_js_source() -> str:
    """Return the generated website/config.js body.

    Kept separate from writing so that the file's content hash is known before
    the pages that reference it are rendered (asset URL versioning below).
    """
    payload = {
        "siteName": C.SITE_NAME,
        "siteUrl": C.SITE_URL,
        "contactEmail": C.CONTACT_EMAIL,
        "contactEmails": list(C.CONTACT_EMAILS),
        "formEndpoint": C.FORM_ENDPOINT or "",
        "githubUrl": C.REPO_URL,
        "listingUrl": C.LISTING_URL,
        "allowlist": list(C.ALLOWED_DOMAINS),
        "recordedDataUrl": "/data/recorded-assessment.json",
    }
    js = (
        "/* ==========================================================================\n"
        "   SMB Scanner Lite - runtime configuration (GENERATED FILE)\n"
        "   --------------------------------------------------------------------------\n"
        "   Do not edit this file by hand. The contact address and form endpoint are\n"
        "   read from site.contact.json at the repository root and this file is\n"
        "   rewritten by `python3 tools/build_site.py`.\n\n"
        "   To change the contact email:\n"
        "     python3 tools/set_contact.py --email you@example.com\n"
        "   or run the \"Change contact email\" workflow from the GitHub Actions tab,\n"
        "   which updates the JSON, rebuilds the site and commits the result.\n\n"
        "   The site has no backend. When formEndpoint is set the enquiry forms POST\n"
        "   to it; when it is empty they compose the message in the visitor's mail\n"
        "   client instead. Neither path stores data on this website.\n"
        "   ========================================================================== */\n"
        "window.SMB_CONFIG = " + json.dumps(payload, indent=2, ensure_ascii=False) + ";\n"
    )
    return js


def build_config_js() -> None:
    """Write website/config.js (generated from site.contact.json)."""
    write("config.js", config_js_source())


def build_data() -> None:
    controls = []
    for control in D.CONTROLS:
        controls.append({
            "num": control["num"],
            "name": control["name"],
            "short": control["short"],
            "cat": control["cat"],
            "category_name": D.category(control["cat"])["name"],
            "weight": control["weight"],
            "summary": control["short"],
            "evaluates": control["evaluates"],
            "why": control["why"],
            "example": control["example"],
            "recorded": control["recorded"],
        })

    payload = {
        "product": C.SITE_NAME,
        "version": C.PRODUCT_VERSION,
        "edition": C.EDITION,
        "policy_version": C.POLICY_VERSION,
        "generated": BUILD_DATE,
        "default": D.RECORDED_DEFAULT,
        "allowed_domains": list(C.ALLOWED_DOMAINS),
        "notice": (
            "Static recorded assessment output. Not a live scan. Values are taken from a "
            "genuine sandbox run on 28 October 2026 for example.com; profiles for the other "
            "four approved domains are reference profiles shipped with runtime v5.2.0."
        ),
        "controls": controls,
        "domains": D.RECORDED,
    }
    write("data/recorded-assessment.json", json.dumps(payload, indent=2, ensure_ascii=False) + "\n")


